-- EloVital: schema inicial gerado a partir do DER (EloVital_DER_atualizado).
-- Convenções: PK BIGINT identity; created_at/updated_at/sincronizado em todas as tabelas;
-- enums guardados como VARCHAR + CHECK; FKs de dados do idoso com ON DELETE CASCADE.

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    tipo_perfil VARCHAR(20) NOT NULL CHECK (tipo_perfil IN ('IDOSO', 'CUIDADOR')),
    telefone VARCHAR(20),
    tamanho_fonte INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE idoso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuario (id) ON DELETE RESTRICT,
    data_nascimento DATE NOT NULL,
    tipo_sanguineo VARCHAR(3),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE vinculo_acesso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idoso_id BIGINT NOT NULL REFERENCES idoso (id) ON DELETE CASCADE,
    usuario_id BIGINT NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    tipo_relacao VARCHAR(20) NOT NULL CHECK (tipo_relacao IN ('FAMILIAR', 'PROFISSIONAL')),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE' CHECK (status IN ('PENDENTE', 'ATIVO', 'REVOGADO')),
    data_expiracao TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (idoso_id, usuario_id)
);

CREATE TABLE alergia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idoso_id BIGINT NOT NULL REFERENCES idoso (id) ON DELETE CASCADE,
    descricao VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE contato_emergencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idoso_id BIGINT NOT NULL REFERENCES idoso (id) ON DELETE CASCADE,
    nome VARCHAR(150) NOT NULL,
    telefone VARCHAR(20) NOT NULL,
    parentesco VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE lembrete_agua (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idoso_id BIGINT NOT NULL REFERENCES idoso (id) ON DELETE CASCADE,
    horario TIME NOT NULL,
    meta_ml INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE registro_agua (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idoso_id BIGINT NOT NULL REFERENCES idoso (id) ON DELETE CASCADE,
    lembrete_agua_id BIGINT REFERENCES lembrete_agua (id) ON DELETE SET NULL,
    data_hora TIMESTAMPTZ NOT NULL,
    quantidade_ml INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE condicao_saude (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idoso_id BIGINT NOT NULL REFERENCES idoso (id) ON DELETE CASCADE,
    medico_nome VARCHAR(150),
    descricao VARCHAR(255) NOT NULL,
    data_diagnostico DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE medicamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idoso_id BIGINT NOT NULL REFERENCES idoso (id) ON DELETE CASCADE,
    medico_nome VARCHAR(150),
    nome VARCHAR(150) NOT NULL,
    dosagem VARCHAR(100),
    foto_url VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE lembrete_medicamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicamento_id BIGINT NOT NULL REFERENCES medicamento (id) ON DELETE CASCADE,
    horario TIME NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE lembrete_dia_semana (
    lembrete_medicamento_id BIGINT NOT NULL REFERENCES lembrete_medicamento (id) ON DELETE CASCADE,
    dia_semana INTEGER NOT NULL CHECK (dia_semana BETWEEN 0 AND 6),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (lembrete_medicamento_id, dia_semana)
);

CREATE TABLE registro_medicamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicamento_id BIGINT NOT NULL REFERENCES medicamento (id) ON DELETE CASCADE,
    lembrete_medicamento_id BIGINT REFERENCES lembrete_medicamento (id) ON DELETE SET NULL,
    data_hora TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('TOMADO', 'ATRASADO', 'PULADO')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE medicao_saude (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idoso_id BIGINT NOT NULL REFERENCES idoso (id) ON DELETE CASCADE,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('PRESSAO', 'GLICEMIA')),
    data_hora TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE pressao_arterial (
    medicao_id BIGINT PRIMARY KEY REFERENCES medicao_saude (id) ON DELETE CASCADE,
    sistolica_mmhg INTEGER NOT NULL,
    diastolica_mmhg INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE glicemia (
    medicao_id BIGINT PRIMARY KEY REFERENCES medicao_saude (id) ON DELETE CASCADE,
    valor_mgdl INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE consulta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idoso_id BIGINT NOT NULL REFERENCES idoso (id) ON DELETE CASCADE,
    medico_nome VARCHAR(150),
    criado_por_usuario_id BIGINT NOT NULL REFERENCES usuario (id) ON DELETE RESTRICT,
    consulta_origem_id BIGINT REFERENCES consulta (id) ON DELETE SET NULL,
    especialidade VARCHAR(100),
    data_hora TIMESTAMPTZ NOT NULL,
    local_atendimento VARCHAR(255),
    observacoes VARCHAR(1000),
    preparo VARCHAR(1000),
    status VARCHAR(20) NOT NULL DEFAULT 'AGENDADA' CHECK (status IN ('AGENDADA', 'REALIZADA', 'CANCELADA', 'FALTEI', 'REMARCADA')),
    anotacao_pos_consulta VARCHAR(4000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE lembrete_consulta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id BIGINT NOT NULL REFERENCES consulta (id) ON DELETE CASCADE,
    antecedencia_minutos INTEGER NOT NULL,
    enviado BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE dispositivo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    token_push VARCHAR(512) NOT NULL UNIQUE,
    plataforma VARCHAR(10) NOT NULL CHECK (plataforma IN ('ANDROID', 'IOS')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE lembrete_medicao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idoso_id BIGINT NOT NULL REFERENCES idoso (id) ON DELETE CASCADE,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('PRESSAO', 'GLICEMIA')),
    horario TIME NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sincronizado BOOLEAN NOT NULL DEFAULT TRUE
);

-- Índices nas FKs (o PostgreSQL não cria automaticamente)
CREATE INDEX idx_vinculo_acesso_idoso_id ON vinculo_acesso (idoso_id);
CREATE INDEX idx_vinculo_acesso_usuario_id ON vinculo_acesso (usuario_id);
CREATE INDEX idx_alergia_idoso_id ON alergia (idoso_id);
CREATE INDEX idx_contato_emergencia_idoso_id ON contato_emergencia (idoso_id);
CREATE INDEX idx_lembrete_agua_idoso_id ON lembrete_agua (idoso_id);
CREATE INDEX idx_registro_agua_idoso_id ON registro_agua (idoso_id);
CREATE INDEX idx_registro_agua_lembrete_agua_id ON registro_agua (lembrete_agua_id);
CREATE INDEX idx_condicao_saude_idoso_id ON condicao_saude (idoso_id);
CREATE INDEX idx_medicamento_idoso_id ON medicamento (idoso_id);
CREATE INDEX idx_lembrete_medicamento_medicamento_id ON lembrete_medicamento (medicamento_id);
CREATE INDEX idx_registro_medicamento_medicamento_id ON registro_medicamento (medicamento_id);
CREATE INDEX idx_registro_medicamento_lembrete_medicamento_id ON registro_medicamento (lembrete_medicamento_id);
CREATE INDEX idx_medicao_saude_idoso_id ON medicao_saude (idoso_id);
CREATE INDEX idx_consulta_idoso_id ON consulta (idoso_id);
CREATE INDEX idx_consulta_criado_por_usuario_id ON consulta (criado_por_usuario_id);
CREATE INDEX idx_consulta_consulta_origem_id ON consulta (consulta_origem_id);
CREATE INDEX idx_lembrete_consulta_consulta_id ON lembrete_consulta (consulta_id);
CREATE INDEX idx_dispositivo_usuario_id ON dispositivo (usuario_id);
CREATE INDEX idx_lembrete_medicao_idoso_id ON lembrete_medicao (idoso_id);
